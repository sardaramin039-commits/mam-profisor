/**
 * Maps input topic and discipline strings to the most relevant domain numbers.
 */
export function identifyRelevantDomains(topic: string, discipline: string): number[] {
  const combined = `${topic} ${discipline}`.toLowerCase();
  const matchedDomainScores: Record<number, number> = {};

  for (let d = 1; d <= 11; d++) {
    matchedDomainScores[d] = 0;
  }

  for (const pt of SUPREME_111_DOCTORAL_DIRECTIVES) {
    for (const kw of pt.frameworkKeywords) {
      if (combined.includes(kw.toLowerCase())) {
        matchedDomainScores[pt.domainNumber] += 2;
      }
    }
  }

  // Ensure default presence of Domain 1 (Discourse), Domain 5 (Philosophy/Logic), and Domain 11 (Crown Jewels)
  matchedDomainScores[1] += 1;
  matchedDomainScores[5] += 1;
  matchedDomainScores[11] += 1;

  // Specific domain boosters
  if (combined.includes("زمان") || combined.includes("ڕێزمان") || combined.includes("linguistic") || combined.includes("grammar") || combined.includes("dialect")) {
    matchedDomainScores[3] += 5;
  }
  if (combined.includes("ئەدەب") || combined.includes("شیعر") || combined.includes("ڕۆمان") || combined.includes("literature") || combined.includes("translation") || combined.includes("وەرگێڕان")) {
    matchedDomainScores[4] += 5;
  }
  if (combined.includes("گەشت") || combined.includes("فەزا") || combined.includes("شوێن") || combined.includes("travelogue") || combined.includes("space")) {
    matchedDomainScores[2] += 5;
  }
  if (combined.includes("میتۆد") || combined.includes("method") || combined.includes("grounded") || combined.includes("کەیس")) {
    matchedDomainScores[8] += 5;
  }
  if (combined.includes("سەرچاوە") || combined.includes("بیبلۆگرافیا") || combined.includes("bibliometric")) {
    matchedDomainScores[6] += 5;
  }
  if (combined.includes("ئەخلاق") || combined.includes("ethics") || combined.includes("ڕەسەن")) {
    matchedDomainScores[9] += 5;
  }

  // Pick top domains (score >= 2)
  const sorted = Object.entries(matchedDomainScores)
    .sort(([, a], [, b]) => b - a)
    .filter(([, score]) => score >= 2)
    .map(([d]) => parseInt(d, 10));

  return sorted.length > 0 ? sorted.slice(0, 5) : [1, 5, 11];
}

/**
 * Returns tailored prompt directives matching the specific academic topic and discipline.
 */
export function getDomainSpecificDirectives(topic: string, discipline: string): string {
  const activeDomains = identifyRelevantDomains(topic, discipline);
  const selectedPoints = SUPREME_111_DOCTORAL_DIRECTIVES.filter(p => activeDomains.includes(p.domainNumber));

  let out = `\n[ماتریکسی ١١١ توانستی باڵای دکتۆرا - پسپۆڕیی دیاریکراو بۆ: "${topic}" (${discipline || "گشتی"})]:\n`;
  out += `* تەوەرە چالاککراوەکان: ${activeDomains.map(d => `تەوەرەی ${d}`).join("، ")}\n\n`;

  const domainGroups: Record<number, SupremeDoctoralPoint[]> = {};
  for (const pt of selectedPoints) {
    if (!domainGroups[pt.domainNumber]) domainGroups[pt.domainNumber] = [];
    domainGroups[pt.domainNumber].push(pt);
  }

  for (const [dNumStr, pts] of Object.entries(domainGroups)) {
    const dNum = parseInt(dNumStr, 10);
    const domainHeader = pts[0]?.domainTitleKurdish || `تەوەرەی ${dNum}`;
    out += `### بەشی ${dNum}: ${domainHeader} (${pts[0]?.domainTitleEnglish})\n`;
    for (const p of pts) {
      out += `* خاڵی ${p.id}. ${p.titleKurdish} [${p.titleEnglish}]:\n`;
      out += `  - ڕێسای زانستی: ${p.systemDirective}\n`;
      out += `  - ڕێنمایی میتۆدی: ${p.methodologicalInstruction}\n`;
    }
    out += "\n";
  }

  return out;
}

/**
 * Returns the entire 111-directive doctoral constitution.
 */
export function getSupremeDoctoralDirective(): string {
  let out = `\n[دەستووری ١١١ توانستی باڵای دکتۆرا - THE 111 NEXT-GEN DOCTORAL CONSTITUTION - TOTAL 211-POINT ENGINE]:\n`;

  const domainGroups: Record<number, SupremeDoctoralPoint[]> = {};
  for (const pt of SUPREME_111_DOCTORAL_DIRECTIVES) {
    if (!domainGroups[pt.domainNumber]) domainGroups[pt.domainNumber] = [];
    domainGroups[pt.domainNumber].push(pt);
  }

  for (const [dNumStr, pts] of Object.entries(domainGroups)) {
    const dNum = parseInt(dNumStr, 10);
    const domainHeader = pts[0]?.domainTitleKurdish || `تەوەرەی ${dNum}`;
    out += `\n### پۆلی ${dNum}: ${domainHeader} (${pts[0]?.domainTitleEnglish})\n`;
    for (const p of pts) {
      out += `* ${p.id}. ${p.titleKurdish} (${p.titleEnglish}): ${p.systemDirective} [ڕێنمایی: ${p.methodologicalInstruction}]\n`;
    }
  }

  return out;
}

/**
 * Returns the combined 211-point directive: 100 Classical Points + 111 Next-Gen Doctoral Points.
 */
export function getUnified211AcademicDirectives(topic: string = "", discipline: string = ""): string {
  const specific111 = topic ? getDomainSpecificDirectives(topic, discipline) : getSupremeDoctoralDirective();
  return `${specific111}\n\n[بنەما تەلارسازی و زانستییە تەواوکەرەکان - ٢١١ خاڵی یەکگرتوو بەردەوام چالاکن].`;
}
